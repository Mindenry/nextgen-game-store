export type TranslationKey = keyof typeof dict;

const dictAny = dict as Record<string, { th: string; en: string }>;

export const getLocale = cache(async (): Promise<Locale> => {
  const store = await cookies();
  const value = store.get(LANG_COOKIE)?.value;
  if (value === "en" || value === "th") return value;
  const fallback = await getSetting<Locale>("store.language", "th");
  return fallback === "en" ? "en" : "th";
});

export function translate(locale: Locale, key: TranslationKey | string, vars?: Record<string, string | number>): string {
  const entry = dictAny[key];
  let text = entry ? entry[locale] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

/** For server components. */
export async function t(key: TranslationKey | string, vars?: Record<string, string | number>): Promise<string> {
  const locale = await getLocale();
  return translate(locale, key, vars);
}

export function localizedName(
  row: { name_th?: string | null; name_en?: string | null; name?: string | null },
  locale: Locale,
): string {
  if (locale === "th") return row.name_th || row.name_en || row.name || "—";
  return row.name_en || row.name_th || row.name || "—";
}
