#!/usr/bin/env node
/**
 * Creates .env.local with strong random secrets if it does not exist.
 * Never overwrites an existing file.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const target = resolve(root, ".env.local");
const example = readFileSync(resolve(root, ".env.example"), "utf8");

if (existsSync(target)) {
  console.log(".env.local already exists — leaving it untouched.");
  process.exit(0);
}

const generated = {
  ENCRYPTION_KEY: randomBytes(32).toString("base64"),
  CART_COOKIE_SECRET: randomBytes(48).toString("base64url"),
  PAYMENT_WEBHOOK_SECRET: randomBytes(32).toString("hex"),
  CRON_SECRET: randomBytes(32).toString("hex"),
  BOOTSTRAP_ADMIN_PASSWORD: "Admin#" + randomBytes(6).toString("base64url"),
  SEED_DEMO: "true",
};

let out = example;
for (const [key, value] of Object.entries(generated)) {
  out = out.replace(new RegExp(`^${key}=.*$`, "m"), `${key}="${value}"`);
}
out += `\n# Generated by scripts/init-env.mjs on ${new Date().toISOString()}\n`;
writeFileSync(target, out, { encoding: "utf8", mode: 0o600 });
console.log("Created .env.local");
console.log("Bootstrap admin password:", generated.BOOTSTRAP_ADMIN_PASSWORD);
console.log("Store it securely — it is only printed once.");
